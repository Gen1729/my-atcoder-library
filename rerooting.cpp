// 子部分木を合成する関数
mint merge(mint a, mint b){
    return a * b;
}

// mergeの単位元（子部分木が存在しない場合）
mint e(){
    return mint(1);
}

// 辺を遡って親頂点につながる時の関数　V→E
mint put_edge(mint v, int i){
    return v + 1;
}

// 親頂点を含める時の関数　E→V
mint put_vertex(mint e, int v){
    return e;
}

