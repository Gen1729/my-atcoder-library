template<class T>
struct Run {
    T value;
    ll l, r;

    ll len() const {
        return r - l;
    }
};

// 配列
template<class T>
vector<Run<T>> rle(const vector<T>& v) {
    vector<Run<T>> res;

    ll n = (ll)v.size();

    for (ll l = 0; l < n;) {
        ll r = l + 1;

        while (r < n && v[l] == v[r]) {
            r++;
        }

        res.push_back({v[l], l, r});

        l = r;
    }

    return res;
}

// 文字列
vector<Run<char>> rle(const string& s) {
    vector<Run<char>> res;

    ll n = (ll)s.size();

    for (ll l = 0; l < n;) {
        ll r = l + 1;

        while (r < n && s[l] == s[r]) {
            r++;
        }

        res.push_back({s[l], l, r});

        l = r;
    }

    return res;
}

